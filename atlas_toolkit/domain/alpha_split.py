_TOP = np.zeros(256, np.uint8)
_BOTTOM = np.zeros(256, np.uint8)
for _a, (_t, _b) in SPLIT.items():
    _TOP[_a], _BOTTOM[_a] = _t, _b


def split_alphas(alpha: np.ndarray, holders: np.ndarray) -> np.ndarray:
    """Per-layer alpha for K stacked layers (index 0 = top).

    alpha: uint8 (H, W), the composite's alpha. holders: bool (K, H, W),
    True where that layer's hull covers the pixel. Opaque pixels go to every
    holder; a semi-transparent pixel is handed out top-down: each holder
    takes SPLIT[remaining][0] and leaves SPLIT[remaining][1] below, except
    the last holder (or remaining < 2), which takes all that is left."""
    alpha = np.asarray(alpha, dtype=np.uint8)
    holders = np.asarray(holders, dtype=bool)
    out = np.zeros(holders.shape, np.uint8)
    opaque = alpha == 255
    remaining = np.where(opaque, 0, alpha).astype(np.uint8)
    below = holders.sum(axis=0)
    for k in range(holders.shape[0]):
        held = holders[k]
        below = below - held
        split = held & ~opaque & (below >= 1) & (remaining >= 2)
        take_all = held & ~opaque & ~split
        out[k] = np.where(held & opaque, 255, np.where(split, _TOP[remaining], np.where(take_all, remaining, 0)))
        remaining = np.where(split, _BOTTOM[remaining], np.where(take_all, 0, remaining)).astype(np.uint8)
    return out
